  const proposalsCol = collection(db, 'proposals');
  const q = query(proposalsCol, orderBy('timestamp', 'desc'));
  const snap = await getDocs(q);
  return snap.docs.map(d => ({ id: d.id, ...d.data() } as SavedProposal));
