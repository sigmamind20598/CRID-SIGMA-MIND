/**
 * Admin Panel: Approves or rejects a payment and updates user status.
 */
export async function updatePaymentStatus(paymentId: string, status: 'approved' | 'rejected', userEmail: string): Promise<void> {
  const paymentRef = doc(db, 'payments', paymentId);
  await updateDoc(paymentRef, { status });
  
  if (status === 'approved') {
    // Automatically unlock the user's premium status!
    await saveUserProfile({
      email: userEmail,
      premiumUnlocked: true
    });
  }
}

/**
 * Admin Panel: Manually toggles a user's premium status.
 */
export async function updateUserPremiumStatus(email: string, premiumUnlocked: boolean): Promise<void> {
  await saveUserProfile({
    email,
    premiumUnlocked
  });
}
